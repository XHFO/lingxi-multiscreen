static bool terminal_use_smooth(const c6_renderer_t *r){return r->smooth_digits||C6_TERMINAL_AERO_DIGITS==2;}
static unsigned terminal_smooth_sample(unsigned digit,int x,int y){
    if(x<0||x>=42||y<0||y>=60)return 0;
    unsigned i=(unsigned)y*42+(unsigned)x;return ((terminal_smooth_aero[digit][i/2]>>(i%2?0:4))&15)*17;
}
static unsigned terminal_smooth_alpha(unsigned digit,int sx,int sy){
    int x=sx>=0?sx/256:-1,y=sy>=0?sy/256:-1;unsigned fx=(unsigned)(sx-x*256),fy=(unsigned)(sy-y*256);
    unsigned a=terminal_smooth_sample(digit,x,y)*(256-fx)+terminal_smooth_sample(digit,x+1,y)*fx;
    unsigned b=terminal_smooth_sample(digit,x,y+1)*(256-fx)+terminal_smooth_sample(digit,x+1,y+1)*fx;
    return (a*(256-fy)+b*fy+32768)>>16;
}
