#!/usr/bin/env python3
"""Build an offline schematic dot map from Natural Earth public-domain GeoJSON.
Input is explicit; the generator never downloads data or accesses user settings.
"""
import argparse, hashlib, json, math
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument('geojson', type=Path)
parser.add_argument('output', type=Path)
args = parser.parse_args()
source = args.geojson.read_bytes()
features = json.loads(source)['features']
columns, rows = 120, 52
polygons = []
for feature in features:
    props, geometry = feature['properties'], feature['geometry']
    code = props.get('ISO_A2_EH') or props.get('ISO_A2')
    if not code or len(code) != 2:
        code = {'France': 'FR', 'Norway': 'NO', 'Kosovo': 'XK'}.get(props.get('ADMIN'))
    if not code or code in {'ZZ', 'XX'}:
        continue
    values = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
    for polygon in values:
        outer = polygon[0]
        xs, ys = zip(*outer)
        polygons.append((code, polygon, (min(xs), min(ys), max(xs), max(ys))))

def inside_ring(x, y, ring):
    inside = False
    a = ring[-1]
    for b in ring:
        if (a[1] > y) != (b[1] > y):
            if x < (b[0]-a[0]) * (y-a[1]) / (b[1]-a[1]) + a[0]: inside = not inside
        a = b
    return inside

groups = {}
for row in range(rows):
    latitude = 84 - (row + .5) / rows * 140
    squeeze = math.cos(math.radians(latitude * .35))
    for column in range(columns):
        longitude = ((column + .5) / columns - .5) * 360 / squeeze
        if abs(longitude) > 180: continue
        for code, polygon, box in polygons:
            if not (box[0] <= longitude <= box[2] and box[1] <= latitude <= box[3]): continue
            if inside_ring(longitude, latitude, polygon[0]) and not any(inside_ring(longitude, latitude, hole) for hole in polygon[1:]):
                groups.setdefault(code, []).append(row * columns + column)
                break
# Small island/territory anchors omitted by the 1:110m data and the dot grid.
owners = {dot: code for code, dots in groups.items() for dot in dots}
anchors = set()
for code, (lon, lat) in {'SG':(103.82,1.35),'HK':(114.17,22.32),'MO':(113.54,22.2),
    'TW':(121,23.7),'MT':(14.4,35.9),'MV':(73.2,3.2),'BH':(50.55,26.05),
    'LU':(6.1,49.8),'AD':(1.5,42.5),'LI':(9.55,47.1),'MC':(7.4,43.7),
    'MU':(57.55,-20.3),'SC':(55.45,-4.65),'BB':(-59.5,13.2),'BM':(-64.75,32.3),
    'CV':(-23.7,15.1),'RE':(55.5,-21.1),'GU':(144.8,13.45)}.items():
    if code in groups: continue
    col = min(columns-1, max(0, int((lon * math.cos(math.radians(lat * .35)) / 360 + .5)*columns)))
    row = min(rows-1, max(0, int((84-lat)/140*rows)))
    # Reserve one nearby schematic cell. Never alpha-stack territories or erase
    # the last remaining cell of a neighbouring country at this coarse scale.
    candidates = sorted(((dy, dx) for dy in range(-2, 3) for dx in range(-2, 3)),
                        key=lambda offset: (offset[0]**2 + offset[1]**2, offset))
    for dy, dx in candidates:
        if not (0 <= row + dy < rows and 0 <= col + dx < columns): continue
        dot = (row + dy) * columns + col + dx
        owner = owners.get(dot)
        if dot in anchors or (owner and len(groups[owner]) == 1): continue
        if owner: groups[owner].remove(dot)
        groups[code] = [dot]
        owners[dot] = code
        anchors.add(dot)
        break
    else:
        raise ValueError('No exclusive schematic anchor for ' + code)
all_dots = [dot for dots in groups.values() for dot in dots]
assert len(all_dots) == len(set(all_dots)), 'Countries must never share a rendered dot'
text = '''// Natural Earth 1:110m schematic land dots; public domain. See docs/CLOUDFLARE-WORLD-MAP.md.
// Generated by scripts/build-cloudflare-world-dots.py; no network access at runtime.
import Foundation

enum CloudflareWorldDots {
    static let columns = 120
    static let rows = 52
    static let sourceSHA256 = "%s"
    static let countries: [String: [UInt16]] = [
''' % hashlib.sha256(source).hexdigest()
for code, dots in sorted(groups.items()):
    text += '        "%s": [%s],\n' % (code, ','.join(map(str,dots)))
text += '    ]\n}\n'
args.output.write_text(text)
print(f'{sum(map(len,groups.values()))} dots, {len(groups)} regions; {len(text)} bytes')
