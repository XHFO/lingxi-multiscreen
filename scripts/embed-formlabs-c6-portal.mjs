import {readFileSync,writeFileSync} from 'node:fs';
import vm from 'node:vm';
const root=new URL('../',import.meta.url);
const style=readFileSync(new URL('Tools/FormlabsC6Firmware/web/portal.css',root),'utf8');
const hash=readFileSync(new URL('Tools/FormlabsC6Firmware/web/sha256.js',root),'utf8');
const i18n=readFileSync(new URL('Tools/FormlabsC6Firmware/web/i18n.js',root),'utf8');
const preview=readFileSync(new URL('Tools/FormlabsC6Firmware/web/preview.js',root),'utf8');
const autosave=readFileSync(new URL('Tools/FormlabsC6Firmware/web/autosave.js',root),'utf8');
const weather=readFileSync(new URL('Tools/FormlabsC6Firmware/web/weather.js',root),'utf8');
const html=readFileSync(new URL('Tools/FormlabsC6Firmware/web/standalone.html',root),'utf8').replace('/* PORTAL_STYLE */',style).replace('/* PORTAL_HASH */',hash).replace('/* PORTAL_I18N */',i18n).replace('/* PORTAL_AUTOSAVE */',autosave).replace('/* PORTAL_PREVIEW */',preview).replace('/* PORTAL_WEATHER */',weather);
const encoded='// Generated by scripts/embed-formlabs-c6-portal.mjs.\nstatic const char standalone_portal[]=\n'+html.split('\n').map(line=>JSON.stringify(line+'\n')).join('\n')+';\n';
const target=new URL('Tools/FormlabsC6Firmware/src/formlabs_portal.h',root);
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==encoded)throw Error('Formlabs portal needs regeneration');}
else writeFileSync(target,encoded);
console.log('Formlabs C6 portal: '+Buffer.byteLength(html)+' bytes');
// The Wi-Fi page does not need the printer/display settings dictionary. Keep
// all literals used by that page or shared helpers, without changing runtime
// translation behavior. This leaves room in the existing OTA partition.
const wifiSource=readFileSync(new URL('Tools/FormlabsC6Firmware/web/wifi.html',root),'utf8');
const dictionaries=vm.runInNewContext(i18n+'\n({uiStrings,uiChinese})');
const used=wifiSource+i18n.slice(i18n.indexOf('function t('));
let wifiI18n=i18n;
for(const name of ['uiStrings','uiChinese']){
    const begin=wifiI18n.indexOf('const '+name+'={'),end=wifiI18n.indexOf('\n};',begin)+3;
    const entries=Object.entries(dictionaries[name]).filter(([key])=>used.includes(key));
    wifiI18n=wifiI18n.slice(0,begin)+'const '+name+'='+JSON.stringify(Object.fromEntries(entries))+';'+wifiI18n.slice(end);
}
const wifi=wifiSource.replace('/* PORTAL_STYLE */',style).replace('/* PORTAL_I18N */',wifiI18n);
const wifiEncoded='// Generated by scripts/embed-formlabs-c6-portal.mjs.\nstatic const char portal[]=\n'+wifi.split('\n').map(line=>JSON.stringify(line+'\n')).join('\n')+';\n';
const wifiTarget=new URL('Tools/FormlabsC6Firmware/src/formlabs_wifi_portal.h',root);
if(process.argv.includes('--check')){if(readFileSync(wifiTarget,'utf8')!==wifiEncoded)throw Error('Formlabs Wi-Fi portal needs regeneration');}
else writeFileSync(wifiTarget,wifiEncoded);
