#!/bin/sh
set -eu
cd "$(dirname "$0")/../.."
output="${1:-.build/readpico-board-ui-render}"
configuration="${2:-Debug}"
mkdir -p "$output"
python3 - "$output" "$configuration" <<'PY'
from pathlib import Path
import hashlib, json, shlex, subprocess, sys
root=Path.cwd(); output=Path(sys.argv[1]).resolve(); config=sys.argv[2]
objects=root/f'.build/out/Intermediates.noindex/LinxDisplay.build/{config}/LinxDisplayApp-p.build/Objects-normal/arm64'
products=root/f'.build/out/Products/{config}'
sdk=subprocess.check_output(['xcrun','--sdk','macosx','--show-sdk-path'],text=True).strip()
source=root/'Sources/LinxDisplayApp/ReadPicoLingxiBoardView.swift'
fixture=output/'ProductionBoardView.swift'
sha=lambda p:hashlib.sha256(Path(p).read_bytes()).hexdigest()
origins=[p for p in (root/'Sources').rglob('*') if p.is_file() and not p.is_symlink()]
origins += [root/'Tools/ReadPicoManagerTests/BoardUIRender.swift', root/'Tools/ReadPicoManagerTests/render-board-ui.sh']
before={str(p.relative_to(root)):sha(p) for p in origins}
# Compile the unmodified production view in the test module so its private
# State can be seeded before hosting; only the import is added for AppModel.
source_text=source.read_text()
# AppModel owns the actual production Session; avoid defining a second fixture type.
view_text=source_text.split('/// App-owned automatic board session.',1)[0]+'/// The reader board follows Oracle'+source_text.split('/// The reader board follows Oracle',1)[1]
fixture.write_text('import LinxDisplayApp\n'+view_text+'''\n
extension ReadPicoLingxiBoardView {
    func seedSelectionForRendering(_ value: Int?, delivery: Bool) -> Self {
        var copy = self
        copy._expandedModule = State(initialValue: value)
        copy._page = State(initialValue: delivery ? .delivery : .content)
        copy._showConnectionOptions = State(initialValue: delivery)
        return copy
    }
}
''')
args=[str(root/'scripts/swiftc-sdk-compat'),'-parse-as-library','-swift-version','5','-module-name','ReadPicoBoardUIRender','-sdk',sdk,'-target','arm64-apple-macosx26.0','-Xfrontend','-disable-access-control','-I',str(objects),'-I',str(products),'-Xcc',f'-fmodule-map-file={root}/.build/out/Intermediates.noindex/LinxDisplay.build/{config}/C6DisplayRenderer-t.build/C6DisplayRenderer.modulemap','-Xcc',f'-I{root}/Sources/C6DisplayRenderer/include',str(root/'Tools/ReadPicoManagerTests/BoardUIRender.swift')]
args += [str(fixture)]
linked=shlex.split((objects/'LinxDisplayApp.LinkFileList').read_text())
linked_before={str(p):sha(p) for p in linked}
product=products/'LinxDisplayApp';product_before=sha(product)
args += linked
args += ['-Xlinker','-e','-Xlinker','_readpico_board_ui_render_main','-o',str(output/'render')]
(output/'compile-command.json').write_text(json.dumps(args,indent=2))
(output/'source.json').write_text(json.dumps({'source':str(source),'sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'configuration':config,'state_initialization':'isolated test fixture only'},indent=2))
subprocess.run(args,check=True)
# Remove only prior screenshots generated by this harness, so repeated scenario counts remain exact.
for prior in (output/'screens').glob('*.png'): prior.unlink()
subprocess.run([str(output/'render'),str(output/'screens')],check=True)
assert before=={str(p.relative_to(root)):sha(p) for p in origins},'Production/test sources changed during render'
assert linked_before=={str(p):sha(p) for p in linked},'Linked App objects changed during render'
assert product_before==sha(product),'App product changed during render'
screens={p.name:sha(p) for p in sorted((output/'screens').glob('*.png'))}
report=json.loads((output/'screens/report.json').read_text());assert report['result']=='PASS'
assert len(screens)==len(report['screens'])
assets=[p.relative_to(output).as_posix() for p in sorted((output/'screens/image-fixture').glob('*')) if p.is_file()]
(output/'source-binding.json').write_text(json.dumps({'result':'PASS','source_sha256':before,'linked_objects':linked_before,
    'debug_product':str(product),'debug_product_sha256':product_before,'configuration':config,'native_ui_screens':len(screens),
    'screens':screens,'image_fixture_artifacts':assets,'fixture_binary_sha256':sha(output/'render'),
    'scope':'Actual production BoardView and shared connection panel from current linked full App objects, isolated test state. Wi-Fi uses injected offline device; options reveal through actual onChange. No packaged App launch, physical device, user configuration or external network.'},indent=2)+'\n')
PY
